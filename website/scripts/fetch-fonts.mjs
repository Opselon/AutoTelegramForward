#!/usr/bin/env node
/**
 * Fetch the two families the design system declares and self-host them.
 *
 * The site has always *declared* 'Inter' and 'JetBrains Mono' but never loaded
 * them, so every page silently rendered in system-ui. This script downloads the
 * latin + latin-ext variable subsets once and writes them into
 * src/assets/fonts/ so Vite fingerprints them and applies the deploy base path.
 *
 * Run: node scripts/fetch-fonts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(__dirname, '../src/assets/fonts');
const tmpDir = path.resolve(__dirname, '../.font-tmp');
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
  { id: 'inter', css: 'family=Inter:wght@400..800', file: 'inter-var' },
  { id: 'mono', css: 'family=JetBrains+Mono:wght@400..700', file: 'jetbrains-mono-var' },
];

// Latin first so the preloaded face is the one nearly every visitor needs.
const SUBSETS = ['latin', 'latin-ext'];

const fetchText = async (url) => {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
};

fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(tmpDir, { recursive: true });

const faces = [];

for (const family of FAMILIES) {
  const css = await fetchText(`https://fonts.googleapis.com/css2?${family.css}&display=swap`);

  // Blocks are preceded by their subset comment: /* latin */ @font-face {...}
  const blocks = css.split('/*').slice(1);
  for (const block of blocks) {
    const subset = block.slice(0, block.indexOf('*/')).trim();
    if (!SUBSETS.includes(subset)) continue;
    const url = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
    if (!url) continue;

    const target = `${family.file}-${subset}.woff2`;
    const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
    fs.writeFileSync(path.join(outDir, target), buf);

    faces.push({
      family: family.id === 'inter' ? 'Inter' : 'JetBrains Mono',
      file: target,
      subset,
      bytes: buf.length,
    });
    console.log(`  ↓ ${target} (${(buf.length / 1024).toFixed(1)} kB)`);
  }
}

// Order matters: browsers pick the last matching face, so latin must come last.
faces.sort((a, b) => (a.subset === 'latin-ext' ? -1 : 1) - (b.subset === 'latin-ext' ? -1 : 1));

const css = `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand. */
/* Self-hosted so the declared families actually load, with no third-party
   request, no render-blocking stylesheet and a stable fingerprint. */

${faces
  .map(
    (f) => `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.family === 'Inter' ? '400 800' : '400 700'};
  font-display: swap;
  src: url('../assets/fonts/${f.file}') format('woff2');
  unicode-range: ${
    f.subset === 'latin'
      ? 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'
      : 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF'
  };
}`,
  )
  .join('\n\n')}
`;

fs.writeFileSync(path.resolve(__dirname, '../src/styles/fonts.css'), css, 'utf8');
fs.rmSync(tmpDir, { recursive: true, force: true });
console.log(`✅ ${faces.length} font files self-hosted, src/styles/fonts.css written.`);
