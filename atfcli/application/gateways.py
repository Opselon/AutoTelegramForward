"""The ports the application layer depends on.

Each protocol here is a *dependency inversion*: the use cases state what they
need ("list the tasks", "mint a token", "run a shell command"), and the
infrastructure layer implements it. Nothing in ``application`` or ``domain``
imports ``infrastructure`` or ``presentation``; that direction is what makes the
use cases testable against an in-memory fake, which is exactly what
``core/tests/test_atfcli_architecture.py`` does.

A protocol here is a *contract*, so it is stated in domain terms — ``create_task``
takes a payload and returns a :class:`~atfcli.domain.models.Task`, never an
``urllib`` response or a JSON blob.
"""

from __future__ import annotations

from typing import Any, Mapping, Protocol, Sequence, runtime_checkable

from ..domain.logs import LogPage, LogPolicyView, LogQuery, LogStats
from ..domain.models import (
    AdminUser,
    AuditEvent,
    DeadLetterItem,
    Finding,
    QueueSnapshot,
    Readiness,
    RoutePath,
    ServiceHealth,
    Session,
    SessionChat,
    SimulationResult,
    Task,
)
from ..domain.resources import Resource, ResourceSpec


@runtime_checkable
class Reporter(Protocol):
    """The output sink an adapter may narrate to.

    ``Console`` satisfies this structurally, so infrastructure never imports
    presentation — the arrow points inward, as the dependency rule requires.
    """

    out: Any

    def register_secret(self, value: Any) -> None: ...
    def redact(self, text: str) -> str: ...
    def paint(self, text: str, *styles: str) -> str: ...
    def line(self, text: str = "") -> None: ...
    def info(self, text: str) -> None: ...
    def ok(self, text: str) -> None: ...
    def warn(self, text: str) -> None: ...
    def fail(self, text: str) -> None: ...
    def step(self, text: str) -> None: ...
    def hint(self, text: str) -> None: ...
    def debug(self, text: str) -> None: ...
    def title(self, text: str) -> None: ...
    def rule(self) -> None: ...
    def raw(self, text: str) -> None: ...
    def json(self, payload: Any) -> None: ...
    def emit(self, payload: Any, human: str | None = None) -> None: ...
    def kv(self, pairs: Any, *, indent: int = 0) -> None: ...
    def table(self, headers: Sequence[str], rows: Sequence[Sequence[str]], *, empty: str = "") -> None: ...
    def banner(self, service: str, status: str, *, good: bool) -> None: ...
    def is_tty(self) -> bool: ...


# ------------------------------------------------------------------------ tasks
class TaskGateway(Protocol):
    """Forwarding tasks, their lifecycle, settings and sources."""

    def list_tasks(self) -> list[Task]: ...
    def create_task(self, payload: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def update_task(self, task_id: str, payload: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def delete_task(self, task_id: str) -> Mapping[str, Any]: ...
    def task_action(self, task_id: str, action: str) -> Mapping[str, Any]: ...
    def duplicate_task(self, task_id: str) -> Mapping[str, Any]: ...
    def set_route_path(self, task_id: str, path: RoutePath) -> Mapping[str, Any]: ...
    def simulate(self, task_id: str, text: str, *, sender: str = "") -> SimulationResult: ...
    def get_settings(self, task_id: str) -> Mapping[str, Any]: ...
    def update_settings(
        self,
        task_id: str,
        values: Mapping[str, Any],
        *,
        replace_all: bool = False,
        resets: Sequence[str] = (),
    ) -> Mapping[str, Any]: ...
    def settings_schema(self) -> Mapping[str, Any]: ...
    def task_logs(self, task_id: str, query: LogQuery) -> LogPage: ...


# --------------------------------------------------------------------- sessions
class SessionGateway(Protocol):
    """Linked Telegram accounts: what they are, what they can see, how to stop."""

    def list_sessions(self) -> list[Session]: ...
    def session_chats(self, session_id: str) -> list[SessionChat]: ...
    def backup_session(self, session_id: str) -> Mapping[str, Any]: ...
    def terminate_session(self, session_id: str) -> Mapping[str, Any]: ...


# ------------------------------------------------------------------------- logs
class LogGateway(Protocol):
    """The central archive, its collection policy and its diagnostics window."""

    def query(self, query: LogQuery) -> LogPage: ...
    def stats(self, *, rule_id: str = "", hours: int = 0) -> LogStats: ...
    def export(self, query: LogQuery, *, fmt: str = "json") -> bytes: ...
    def purge(self, query: LogQuery, *, older_than_days: int) -> Mapping[str, Any]: ...
    def policy(self) -> LogPolicyView: ...
    def update_policy(self, body: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def health(self) -> Mapping[str, Any]: ...
    def diagnostics(self, action: str, *, seconds: int = 0) -> Mapping[str, Any]: ...


# --------------------------------------------------------------------- delivery
class DeliveryGateway(Protocol):
    """The delivery queue and its dead-letter list."""

    def queue(self) -> QueueSnapshot: ...
    def dead_letters(self) -> list[DeadLetterItem]: ...
    def retry_dead_letter(self, message_id: str) -> Mapping[str, Any]: ...
    def purge_dead_letters(self) -> Mapping[str, Any]: ...


# -------------------------------------------------------------------- resources
class ResourceGateway(Protocol):
    """A per-owner CRUD collection (AI configs, prompts, filters)."""

    spec: ResourceSpec

    def list_resources(self) -> list[Resource]: ...
    def create_resource(self, payload: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def update_resource(self, resource_id: str, payload: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def delete_resource(self, resource_id: str) -> Mapping[str, Any]: ...


class PromptGateway(ResourceGateway, Protocol):
    """Prompt templates add a live test against a real AI config."""

    def test_prompt(
        self, *, prompt_id: str, ai_config_id: str, sample_text: str, version: int = 0
    ) -> Mapping[str, Any]: ...


# ----------------------------------------------------------------------- backup
class BackupGateway(Protocol):
    """Whole-installation export and restore."""

    def export(self, *, passphrase: str = "") -> Mapping[str, Any]: ...
    def restore(
        self, bundle: Any, *, passphrase: str = "", overwrite: bool = False
    ) -> Mapping[str, Any]: ...


# ------------------------------------------------------------------------ admin
class AdminGateway(Protocol):
    """The administrator control plane."""

    def overview(self) -> Mapping[str, Any]: ...
    def list_users(self, *, limit: int = 50, offset: int = 0) -> list[AdminUser]: ...
    def set_user_status(self, user_id: str, status: str) -> Mapping[str, Any]: ...
    def broadcast(self, message: str) -> Mapping[str, Any]: ...
    def settings(self) -> Mapping[str, Any]: ...
    def save_settings(self, values: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def list_admins(self) -> list[AdminUser]: ...
    def add_admin(self, user_id: str, *, username: str = "") -> Mapping[str, Any]: ...
    def remove_admin(self, user_id: str) -> Mapping[str, Any]: ...
    def extensions(self) -> list[Mapping[str, Any]]: ...
    def toggle_extension(self, extension_id: str) -> Mapping[str, Any]: ...


# ------------------------------------------------------------------------ audit
class AuditGateway(Protocol):
    """Tenant-scoped audit events."""

    def query(self, params: Mapping[str, Any]) -> list[AuditEvent]: ...


# ------------------------------------------------------------------- operations
class OpsGateway(Protocol):
    """Everything the API can say about the deployment itself."""

    def version(self) -> Mapping[str, Any]: ...
    def service_health(self) -> list[ServiceHealth]: ...
    def readiness(self) -> Readiness: ...
    def env_contract(self) -> Mapping[str, Any]: ...
    def diagnostics(self) -> Mapping[str, Any]: ...
    def stats(self) -> Mapping[str, Any]: ...
    def findings(self) -> list[Finding]: ...
    def pv_responder(self) -> Mapping[str, Any]: ...
    def set_pv_responder(self, payload: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def client_settings(self) -> Mapping[str, Any]: ...
    def save_client_credentials(self, payload: Mapping[str, Any]) -> Mapping[str, Any]: ...
    def ai_providers(self) -> list[Mapping[str, Any]]: ...
    def check_ai_key(self, payload: Mapping[str, Any]) -> Mapping[str, Any]: ...


class FileWriter(Protocol):
    """Writes a file the user explicitly asked for (a backup bundle, an export).

    A port rather than a bare ``open`` so a test can assert on the bytes without
    touching the disk, and so `--dry-run` can be honoured in one place.
    """

    def write_text(self, path: str, text: str) -> None: ...


class HostProbe(Protocol):
    """The machine itself: files, environment, docker, subprocesses.

    Implemented by ``atfcli.infrastructure.host.repo.RepoContext`` and faked in
    tests, so an ops command can be exercised without docker or a checkout.
    """

    root: Any
    dry_run: bool
    assume_yes: bool
    timeout: float
    secrets: set[str]

    def path(self, *parts: str) -> Any: ...
    def exists(self, *parts: str) -> bool: ...
    def env(self, key: str, default: str = "") -> str: ...
    def env_file_values(self) -> Mapping[str, str]: ...
    def version(self) -> str: ...
    def run(self, argv: Sequence[str], **kwargs: Any) -> Any: ...
    def run_streaming(self, argv: Sequence[str], **kwargs: Any) -> int: ...
    def compose(self, *args: str, **kwargs: Any) -> Any: ...
    def docker_info(self, refresh: bool = False) -> Any: ...
    def require_docker(self) -> Any: ...
    def container_running(self, service: str) -> bool: ...
    def container_names(self) -> list[str]: ...
    def running_services(self) -> Mapping[str, bool]: ...
    def container_env(self, service: str, key: str) -> str: ...
    def python(self) -> str: ...
    def confirm(self, question: str, *, default: bool = False) -> bool: ...
    def system_facts(self) -> Mapping[str, Any]: ...
    def json_file(self, path: Any, default: Any = None) -> Any: ...
    def write_text(self, path: Any, text: str) -> None: ...


# ------------------------------------------------------------------ composition
class Gateways(Protocol):
    """The set of gateways a command may reach — the container's public surface."""

    tasks: TaskGateway
    sessions: SessionGateway
    logs: LogGateway
    delivery: DeliveryGateway
    ai: ResourceGateway
    prompts: PromptGateway
    filters: ResourceGateway
    backup: BackupGateway
    admin: AdminGateway
    audit: AuditGateway
    ops: OpsGateway
    host: HostProbe
